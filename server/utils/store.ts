import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import type { AwardConfig, Entry } from "#shared/types/fungpt";

interface State {
  target: number;
  /** Highest percentage ever shown, so the counter never goes backwards. */
  peak: number;
  revealedAt: number | null;
  /** The operator's awards, in ceremony order. */
  awards: AwardConfig[];
  /** How many of them have been revealed so far. */
  awardsRevealed: number;
}

interface Store {
  dir: string;
  entries: Map<string, Entry>;
  state: State;
}

let loading: Promise<Store> | null = null;

function dataDir() {
  return resolve(useRuntimeConfig().dataDir);
}

async function writeJson(path: string, data: unknown) {
  const tmp = `${path}.${Math.random().toString(36).slice(2)}.tmp`;
  await writeFile(tmp, JSON.stringify(data));
  await rename(tmp, path);
}

async function load(): Promise<Store> {
  const dir = dataDir();
  await mkdir(join(dir, "entries"), { recursive: true });
  await mkdir(join(dir, "uploads"), { recursive: true });

  const entries = new Map<string, Entry>();
  for (const name of await readdir(join(dir, "entries"))) {
    if (!name.endsWith(".json")) continue;
    const entry = JSON.parse(await readFile(join(dir, "entries", name), "utf8")) as Entry;
    entries.set(entry.id, entry);
  }

  let state: State = {
    target: Number(useRuntimeConfig().agiTarget) || 40,
    peak: 0,
    revealedAt: null,
    awards: [],
    awardsRevealed: 0,
  };
  try {
    state = { ...state, ...JSON.parse(await readFile(join(dir, "state.json"), "utf8")) };
  } catch {
    // First boot.
  }

  return { dir, entries, state };
}

export function useStore() {
  loading ??= load();
  return loading;
}

export function newId(bytes = 12) {
  return Buffer.from(crypto.getRandomValues(new Uint8Array(bytes))).toString("base64url");
}

export function uploadPath(store: Store, fileId: string) {
  // Ids are generated by us, but never trust a path segment anyway.
  if (!/^[\w-]+$/.test(fileId)) throw createError({ statusCode: 400 });
  return join(store.dir, "uploads", fileId);
}

export async function saveEntry(store: Store, entry: Entry) {
  store.entries.set(entry.id, entry);
  await writeJson(join(store.dir, "entries", `${entry.id}.json`), entry);
}

export async function saveState(store: Store) {
  await writeJson(join(store.dir, "state.json"), store.state);
}

export async function wipeStore() {
  const store = await useStore();
  await rm(join(store.dir, "entries"), { recursive: true, force: true });
  await rm(join(store.dir, "uploads"), { recursive: true, force: true });
  await rm(join(store.dir, "state.json"), { force: true });
  loading = null;
  await useStore();
}
